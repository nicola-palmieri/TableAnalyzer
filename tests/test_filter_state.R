library(testthat)
library(shiny)
library(DT)
source("../R/shared_analysis_helpers.R")
source("../R/mod_filter_main.R")

test_that("clearing all filter columns discards their stored settings", {
  data <- data.frame(group = c("A", "A", "B", "B"), value = c(1, 2, 3, 4))
  testServer(mod_filter_server, args = list(uploaded_data = reactive(data)), {
    session$flushReact()
    session$setInputs(columns = c("group", "value"))
    expect_setequal(active_cols(), c("group", "value"))
    session$setInputs(filter_group = "A", min_value = 2, max_value = 4)
    expect_equal(filtered_df(), data[2, , drop = FALSE])
    session$setInputs(columns = NULL)
    expect_equal(filtered_df(), data)
    expect_length(active_cols(), 0)
    expect_null(filter_state$group)
    expect_null(filter_state$value)
    session$setInputs(columns = c("group", "value"))
    expect_equal(filter_state$group$selected, c("A", "B"))
    expect_equal(filter_state$value$min, 1)
    expect_equal(filter_state$value$max, 4)
  })
})
